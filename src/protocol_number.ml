  | Ssh_cert_type_user -> 1l
  | Ssh_cert_type_host -> 2l

let int_to_ssh_cert_type = function
  | 1l -> Some Ssh_cert_type_user
  | 2l -> Some Ssh_cert_type_host
  | _ -> None
